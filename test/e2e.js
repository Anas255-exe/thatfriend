// Headless end-to-end run of the whole flow (offline planner unless LLM_MODE=auto is set).
process.env.LLM_MODE ||= 'offline';
const { config } = await import('../src/config.js');
config.bookingDelayMs = 10;
const { Engine } = await import('../src/engine.js');

const e = new Engine();
const ORG = 'web:organizer';
let otp = null;
const out = [];
e.on('message', m => { if (!m.echo) out.push(m); });
e.on('sms', s => { otp = s.text.match(/\d{6}/)[0]; });
e.on('log', l => console.log('   ·', l.text));
const say = async (key, text) => { console.log(`\n> ${key}: ${text}`); await e.handle(key, text, { channel: 'web', name: key === ORG ? 'Haseeb' : undefined }); };
const last = (key) => out.filter(m => m.to === key).at(-1)?.text || '';
const assert = (c, msg) => { if (!c) { console.error('❌ FAIL:', msg); process.exit(1); } console.log('✔', msg); };

e.registerUser(ORG, 'Haseeb', 'web', ORG);
await say(ORG, 'I want to go to Uti next weekend with Aman, Riya and Kabir. Budget 15k per person');
const t = e.tripOf(ORG);
assert(t.brief.destination === 'Ooty', 'destination parsed (Uti → Ooty)');
assert(t.brief.budgetPerPerson === 15000, 'budget parsed');
assert(t.brief.groupSize === 4, 'group of 4');
assert(t.options.length === 3, '3 itinerary options');
await say(ORG, 'pick:A');
assert(t.chosen?.id === 'A', 'option A chosen');
await say(ORG, 'add the toy train please');
assert(t.chosen.activities.some(a => /railway/i.test(a.name)), 'refinement applied');
await say(ORG, 'ask_squad');
assert(t.stage === 'FRIENDS', 'friends being polled');
assert(out.some(m => m.to === 'web:friend-aman'), 'Aman got a DM');
await say('web:friend-aman', "I'm in! but can we keep it cheap");
await say('web:friend-riya', 'yes, veg food please');
await say('web:friend-kabir', "I'm in");
assert(t.stage === 'APPROVAL', 'moved to approval after all replies');
assert(t.cart.total > 0, `cart total ₹${t.cart.total}`);
// Flagsmith: lower the auto-book limit + turn on the outage drill for this demo run.
const { setOverride } = await import('../src/flags.js');
// Kill switch: payments OFF → checkout blocked, no OTP, cart kept.
setOverride('payments_enabled', { enabled: false });
await say(ORG, 'approve');
assert(t.stage === 'APPROVAL' && !otp && /Payments are paused/.test(last(ORG)), 'kill switch payments_enabled=OFF blocks checkout');
setOverride('payments_enabled', null);
setOverride('auto_book_limit', { enabled: true, value: 10000 });
setOverride('booking_failure_drill', { enabled: true });
await say(ORG, 'approve');
assert(t.stage === 'GATE', 'Flagsmith limit → NudgeBee approval gate');
await say(ORG, 'nb_approve');
await new Promise(r => setTimeout(r, 50));
assert(t.stage === 'OTP' && otp, 'OTP requested after sign-off');
await say(ORG, '000000');
assert(/wrong OTP/.test(last(ORG)), 'wrong OTP rejected');
await say(ORG, otp);
assert(t.stage === 'DONE', 'trip booked');
assert(t.confirmations.every(c => c.ref && c.status === 'confirmed'), `${t.confirmations.length} confirmations with refs`);
assert(t.confirmations.find(c => c.kind === 'stay').provider.endsWith('-Alt'), 'runbook failed over the stay to alternate provider');
assert(t.friends.find(f => f.name === 'Riya').lang === 'ta-IN', 'Riya messaged in Tamil');
assert(/upi:\/\/pay/.test(last('web:friend-riya')), 'friend got UPI share request');
console.log('\n--- final organizer message ---\n' + last(ORG));
console.log('\n✅ E2E PASSED');
